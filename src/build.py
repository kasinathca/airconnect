"""Build the complete deterministic AirConnect India v2.0 analysis artifact."""
from __future__ import annotations

from pathlib import Path
import json

import numpy as np
import pandas as pd

from modeling import run_classification, run_clustering, run_regression
from pipeline import UPSTREAM_COMMIT, build_monthly_features, latest_airport_features, load_and_validate


ROOT = Path(__file__).resolve().parents[1]


def _json_default(value):
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return None if not np.isfinite(value) else float(value)
    raise TypeError(type(value).__name__)


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)


def run() -> dict:
    source = load_and_validate(ROOT)
    monthly, yearly, quarterly = source["monthly"], source["yearly"], source["quarterly"]
    panel = build_monthly_features(monthly)
    latest = latest_airport_features(monthly, yearly)
    regression = run_regression(panel)
    classification = run_classification(panel)
    clustering = run_clustering(latest)

    national = yearly.pivot_table(index="year", columns="category", values="passengers", aggfunc="sum").reset_index()
    national.columns.name = None
    national = national[(national.year >= 2016) & (national.year <= 2025)].fillna(0)
    historical = [{"year": int(row.year), "domestic": int(row.domestic), "international": int(row.international)} for row in national.itertuples()]

    coords = pd.read_csv(ROOT / "data" / "raw" / "airport_coordinates_2025.csv").set_index("airport")
    annual = yearly[(yearly.year >= 2022) & (yearly.year <= 2025)].pivot_table(index=["year", "airport"], columns="category", values="passengers", aggfunc="sum").reset_index()
    annual.columns.name = None
    for name in ["domestic", "international"]:
        annual[name] = annual.get(name, 0).fillna(0).astype(int)
    annual["total"] = annual.domestic + annual.international
    airports = []
    for row in annual.itertuples():
        item = {"year": int(row.year), "code": row.airport, "domestic": int(row.domestic), "international": int(row.international), "total": int(row.total)}
        if row.year == 2025 and row.airport in clustering["airport_clusters"]:
            item["cluster"] = clustering["airport_clusters"][row.airport]
        if row.airport in coords.index:
            item["lat"] = round(float(coords.loc[row.airport, "latitude"]), 3)
            item["lon"] = round(float(coords.loc[row.airport, "longitude"]), 3)
        airports.append(item)

    coverage = monthly.groupby("year").agg(rows=("airport", "size"), airports=("airport", "nunique"), months=("month", "nunique")).reset_index()
    dataset = {
        "metadata": {
            "name": "AirConnect India", "version": "2.0.0", "generated_on": "2026-10-19",
            "traffic_scope": "airport passenger movements (arrivals plus departures)",
            "source": "Kubicek (2026), India Aviation Stats; cleaned DGCA data",
            "source_repository": "https://github.com/mkubicek/india-aviation-stats",
            "source_commit": UPSTREAM_COMMIT, "source_hashes": source["hashes"],
            "monthly_rows": len(monthly), "monthly_airports": int(monthly.airport.nunique()),
            "monthly_coverage": [int(monthly.year.min()), int(monthly.year.max())],
            "model_coverage": [str(panel.date.min().date()), str(panel.date.max().date())], "random_seed": 37,
            "missing_policy": "Targets are never imputed; exact-calendar lag gaps remain missing; feature imputation is fitted on training data only",
            "wape_definition": "sum(abs(actual - predicted)) / sum(abs(actual)); undefined for a zero denominator",
        },
        "source_coverage": coverage.to_dict("records"), "historical": historical, "airports": airports,
        "government": {"operational_2014": 74, "operational_2026": 165, "as_of": "7 July 2026",
                       "note": "Operational aviation facilities are not identical to traffic-reporting airports."},
        "regression": regression, "classification": classification,
        "clustering": {key: value for key, value in clustering.items() if key != "airport_clusters"},
    }
    json_text = json.dumps(dataset, indent=2, ensure_ascii=False, default=_json_default, allow_nan=False) + "\n"
    compact = json.dumps(dataset, separators=(",", ":"), ensure_ascii=False, default=_json_default, allow_nan=False)
    _write_text(ROOT / "data" / "processed" / "analysis.json", json_text)
    _write_text(ROOT / "site" / "assets" / "data.js", "/* Generated by src/build.py from pinned DGCA-derived source files; do not hand-edit. */\nwindow.AIRCONNECT_DATA = " + compact + ";\n")
    panel.to_csv(ROOT / "data" / "processed" / "airport_month_features.csv", index=False, lineterminator="\n")
    latest.to_csv(ROOT / "data" / "processed" / "airport_2025_features.csv", index=False, lineterminator="\n")
    print(json.dumps({"monthly_rows": len(monthly), "model_rows": len(panel),
                      "regression_selected": regression["selected_model"], "regression_beats_baseline": regression["beat_best_test_baseline"],
                      "classification_selected": classification["selected_model"], "cluster_k": clustering["k"],
                      "cluster_silhouette": clustering["silhouette"]}, indent=2))
    return dataset


if __name__ == "__main__":
    run()
